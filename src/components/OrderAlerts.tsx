const KEY = "foodporter-alerts";
let ctx: AudioContext | null = null;

const SOUND_URL = `${process.env.NEXT_PUBLIC_BASE_PATH ?? ""}/sounds/beep-beep.wav`;
let audioEl: HTMLAudioElement | null = null;
let beepSeq = 0; // a real beep during the unlock must not be paused by it
type W = Window & { __fpBeeps?: number; __fpPlays?: number; __fpSynth?: number };

function sound(): HTMLAudioElement | null {
  if (typeof Audio === "undefined") return null;
  if (!audioEl) { audioEl = new Audio(SOUND_URL); audioEl.preload = "auto"; }
  return audioEl;
}

/** Ask iOS Safari 17+ to treat our sound as playback, so the ring/silent switch doesn't mute it. */
function playbackSession() {
  const s = (navigator as unknown as { audioSession?: { type: string } }).audioSession;
  if (s && s.type !== "playback") { try { s.type = "playback"; } catch { /* ignore */ } }
}

/** Unlock audio on the first tap anywhere (iOS/Chrome only allow sound after a user gesture). */
export function unlockAudioOnFirstTap() {
  if (typeof window === "undefined") return;
  const unlock = () => {
    playbackSession();
    const a = sound();
    const seq = beepSeq;
    if (a) { a.muted = true; a.play().then(() => { if (beepSeq === seq) { a.pause(); a.currentTime = 0; } a.muted = false; }).catch(() => { a.muted = false; }); }
    try { ctx ??= new AudioContext(); void ctx.resume(); } catch { /* ignore */ }
  };
  window.addEventListener("pointerdown", unlock, { once: true, capture: true });
}

/**
 * Original "beep-beep" (cartoon style, generated by scripts/tools/make-beep.py, no third-party audio).
 * Plays the WAV through an <audio> element (most reliable on phones); if that's refused, falls back to the same
 * chirps synthesized with Web Audio.
 */
export function beep() {
  const w = window as W;
  w.__fpBeeps = (w.__fpBeeps ?? 0) + 1;
  beepSeq++;
  playbackSession();
  const a = sound();
  if (a) {
    try {
      a.muted = false; a.currentTime = 0;
      w.__fpPlays = (w.__fpPlays ?? 0) + 1;
      const p = a.play();
      if (p && typeof p.catch === "function") { p.catch(() => synth()); }
      return;
    } catch { /* fall through */ }
  }
  synth();
}

function synth() {
  try {
    ctx ??= new AudioContext();
    const c = ctx;
    const go = () => {
      const t0 = c.currentTime + 0.02;
      const comp = c.createDynamicsCompressor();
      comp.threshold.value = -10; comp.ratio.value = 4;
      const master = c.createGain(); master.gain.value = 0.9;
      master.connect(comp).connect(c.destination);
      const chirp = (start: number, f0: number, f1: number) => {
        for (const [type, vol] of [["square", 0.35], ["triangle", 0.6]] as const) {
          const o = c.createOscillator(), g = c.createGain();
          o.type = type;
          o.frequency.setValueAtTime(f0, start);
          o.frequency.exponentialRampToValueAtTime(f1, start + 0.11);
          o.frequency.exponentialRampToValueAtTime(f1 * 0.97, start + 0.16);
          g.gain.setValueAtTime(0.0001, start);
          g.gain.exponentialRampToValueAtTime(vol, start + 0.012);
          g.gain.setValueAtTime(vol, start + 0.12);
          g.gain.exponentialRampToValueAtTime(0.0001, start + 0.17);
          o.connect(g).connect(master);
          o.start(start); o.stop(start + 0.18);
        }
      };
      chirp(t0, 740, 1180);
      chirp(t0 + 0.22, 880, 1480);
      (window as W).__fpSynth = ((window as W).__fpSynth ?? 0) + 1;
    };
    // Schedule only after resume() has finished, otherwise a suspended context drops the notes.
    if (c.state === "running") go(); else void c.resume().then(go).catch(() => {});
  } catch { /* audio not available */ }
}

