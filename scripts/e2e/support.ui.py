# Support UI: customer Hulp sheet (FAQ, category, photo, partial refund) → thread; admin inbox/detail, canned reply,
# realtime reply on the customer side, refund via order-refund; rider SOS; restaurant buttons; reports tab.
import re, sys, json, subprocess
from playwright.sync_api import sync_playwright
creds = dict(l.split("=",1) for l in open(__import__("os").environ.get("FP_TEST_CREDS","/workspace/fptest/.creds")).read().strip().split("\n"))
B = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8787/foodporter-app"
S = "/workspace/foodporter/screens/v12_"; res = []
def ok(n, c, x=""): res.append(c); print(("PASS " if c else "FAIL ") + n + (f" — {x}" if x else ""))
def login(pg, role):
    pg.goto(B + "/login/"); pg.wait_for_load_state("networkidle")
    pg.fill("input[type=email]", creds[role+"_EMAIL"]); pg.fill("input[type=password]", creds[role+"_PASSWORD"])
    pg.get_by_role("button", name=re.compile("^(Inloggen|Sign in)$")).click(); pg.wait_for_timeout(3500)
NODE = lambda js: subprocess.run(["node", "--input-type=module", "-e", "import * as m from '/workspace/foodporter-app/scripts/e2e/common.mjs';" + js], capture_output=True, text=True).stdout.strip().split("\n")[-1]
oid = NODE("const a=await m.login('ADMIN'), c=await m.login('SIMC1'); const {data}=await a.sb.from('orders').select('id').eq('customer_id',c.id).eq('status','delivered').like('mollie_payment_id','tr_sim%').not('lat','is',null).order('id',{ascending:false}).limit(40); const {data:tk}=await a.sb.from('support_tickets').select('order_id').not('order_id','is',null); const used=new Set([1043,1046,...(tk??[]).map(x=>x.order_id)]); console.log((data.find(o=>!used.has(o.id))??data[0]).id); process.exit(0)")
with sync_playwright() as p:
    b = p.chromium.launch()
    mob = dict(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
    cu = b.new_context(**mob).new_page(); errs = []; cu.on("pageerror", lambda e: errs.append(str(e)))
    login(cu, "SIMC1"); cu.goto(B + f"/order/?id={oid}"); cu.wait_for_selector("[data-testid=help-button]", timeout=20000)
    cu.click("[data-testid=help-button]"); cu.wait_for_selector("[data-testid=support-sheet]")
    ok("Hulp sheet opens with a short Dutch FAQ", "Wanneer krijg ik mijn geld terug?" in cu.inner_text("[data-testid=support-sheet]"))
    cu.screenshot(path=S + "customer_help_sheet.png")
    cu.click("[data-testid=cat-missing_item]")
    cu.fill("[data-testid=support-body]", "De friet ontbrak in mijn bestelling.")
    cu.set_input_files("[data-testid=support-photo]", "/tmp/fp_photo.png")
    cu.check("input[name=refund] >> nth=1"); cu.fill("[data-testid=support-amount]", "2,50")
    cu.screenshot(path=S + "customer_help_form.png")
    cu.click("[data-testid=support-submit]"); cu.wait_for_url(re.compile(r"/support/\?id=\d+"), timeout=20000); cu.wait_for_timeout(2500)
    tid = int(re.search(r"id=(\d+)", cu.url).group(1))
    t = cu.inner_text("main")
    ok("ticket created and thread shown (with photo + refund request)", "De friet ontbrak" in t and "€2,50" in t and cu.locator("[data-testid=thread] img").count() == 1, f"#{tid}")
    ad = b.new_context(viewport={"width": 1280, "height": 900}).new_page(); login(ad, "ADMIN")
    ad.goto(B + "/admin/support/"); ad.wait_for_selector("[data-testid=ticket-row]", timeout=20000); ad.wait_for_timeout(2000)
    ok("admin inbox lists the ticket with SLA timer", ad.locator(f"[data-testid=ticket-row]:has-text('#{tid}')").count() == 1 and ad.locator("[data-testid=sla]").count() > 0)
    ad.screenshot(path=S + "admin_support_inbox.png", full_page=True)
    ad.goto(B + f"/admin/support/?id={tid}"); ad.wait_for_selector("[data-testid=admin-thread]", timeout=20000); ad.wait_for_timeout(2500)
    ok("admin detail: photo via signed URL, order timeline, map link, abuse signal", ad.locator("[data-testid=ticket-photo]").count() == 1 and ad.locator("[data-testid=order-timeline] li").count() > 0 and ad.locator("[data-testid=map-link]").count() == 1 and ad.locator("[data-testid=abuse-signal]").count() == 1)
    ad.select_option("select[aria-label='Canned replies']", label="Sorry + refund"); ad.click("text=Send reply"); ad.wait_for_timeout(3500)
    ok("customer sees the admin reply live (realtime, no reload)", cu.locator("[data-testid=msg-admin]").count() >= 1 and "Antwoord ontvangen" in cu.inner_text("[data-testid=ticket-status]"))
    ad.click("text=Assign to me"); ad.wait_for_timeout(1500)
    ok("assign to me", ad.inner_text("[data-testid=assigned]") == "me")
    ad.on("dialog", lambda d: d.accept())
    ad.click("text=Refund via Mollie"); ad.wait_for_timeout(4000)
    ok("refund action via order-refund (simulated test payment)", "simulated" in ad.inner_text("main"))
    ad.screenshot(path=S + "admin_support_ticket.png", full_page=True)
    seen = False
    for _ in range(15):  # realtime delivery can take a few seconds; reload once halfway
        cu.wait_for_timeout(1000)
        if "Terugbetaling van €2,50" in cu.inner_text("[data-testid=thread]"): seen = True; break
        if _ == 7: cu.reload(); cu.wait_for_selector("[data-testid=thread]", timeout=15000)
    ok("customer sees the refund confirmation", seen, cu.inner_text("[data-testid=thread]")[-200:])
    cu.screenshot(path=S + "customer_ticket_thread.png", full_page=True)
    ad.click("text=Resolve"); ad.wait_for_timeout(2000)
    ok("resolve", "Opgelost" in cu.inner_text("[data-testid=ticket-status]"))
    ad.goto(B + "/admin/reports/?tab=support"); ad.wait_for_timeout(1000)
    ad.get_by_role("button", name=re.compile("Support")).first.click(); ad.wait_for_selector("[data-testid=support-count]"); ad.wait_for_timeout(2500)
    ok("support metrics in reports", int(ad.inner_text("[data-testid=support-count]") or 0) > 0)
    ad.screenshot(path=S + "admin_reports_support.png", full_page=True)
    # rider SOS
    NODE("const r=await m.login('RIDER'); await r.sb.from('profiles').update({online:true}).eq('id',r.id); console.log(1); process.exit(0)")
    rc = b.new_context(**mob); rc.grant_permissions(["geolocation"], origin=re.match(r"https?://[^/]+", B).group(0)); rc.set_geolocation({"latitude": 51.5555, "longitude": 5.0913})
    rp = rc.new_page(); login(rp, "RIDER"); rp.goto(B + "/rider/"); rp.wait_for_selector("[data-testid=sos]", timeout=20000); rp.wait_for_timeout(3000)
    rp.screenshot(path=S + "rider_sos.png")
    rp.on("dialog", lambda d: d.accept())
    tel = []; rp.on("request", lambda r: r.url.startswith("tel:") and tel.append(r.url))
    try: rp.click("[data-testid=sos]")
    except Exception: pass
    rp.wait_for_timeout(4000)
    sos = NODE("const a=await m.login('ADMIN'); const {data}=await a.sb.from('support_tickets').select('id,priority,lat').eq('category','sos').order('id',{ascending:false}).limit(1).single(); console.log(JSON.stringify(data)); process.exit(0)")
    ok("SOS: urgent ticket with location + 112 dial attempted", '"urgent"' in sos and '51.55' in sos and rp.evaluate("window.__fpSos||0") == 1, sos)
    NODE("const r=await m.login('RIDER'); await r.sb.from('profiles').update({online:false}).eq('id',r.id); console.log(1); process.exit(0)")
    rp.goto(B + "/rider/earnings/"); rp.wait_for_timeout(2500)
    ok("rider payout question button", rp.locator("[data-testid=help-button]").count() == 1)
    rp.click("[data-testid=help-button]"); rp.wait_for_timeout(500)
    ok("rider categories in Dutch", "Kan het adres niet vinden" in rp.inner_text("[data-testid=support-categories]"))
    rp.screenshot(path=S + "rider_help_sheet.png")
    ok("no page errors on the customer side", not errs, str(errs)[:300])
    b.close()
print(f"{sum(res)}/{len(res)} passed")
